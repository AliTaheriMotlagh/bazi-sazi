import * as THREE from 'three';
import type { ComponentData, EntityData } from '../types';
import { DEG2RAD, errorMessage } from '../util';
import type { Runtime } from './Runtime';
import type { Visual } from './builders';

/**
 * Lifecycle hooks. Scripts, built-in behaviours and visual graphs all
 * implement this same interface (strategy pattern), so the runtime treats
 * every kind of logic identically.
 */
export interface Behaviour {
  start?(): void;
  update?(dt: number): void;
  lateUpdate?(dt: number): void;
  onCollision?(other: GameObject): void;
  onCollisionEnd?(other: GameObject): void;
  onTrigger?(other: GameObject): void;
  onTriggerEnd?(other: GameObject): void;
  onMessage?(name: string, data: unknown, from: GameObject | null): void;
  onClick?(): void;
  onDestroy?(): void;
}

export type HookName = keyof Behaviour;

interface BehaviourSlot {
  source: string;
  impl: Behaviour;
  failed: Set<string>;
}

const _v = new THREE.Vector3();
const _target = new THREE.Vector3();
const _m = new THREE.Matrix4();
const _q = new THREE.Quaternion();
const _pq = new THREE.Quaternion();

export class GameObject {
  readonly id: string;
  name: string;
  readonly tags: Set<string>;
  readonly object3d: THREE.Object3D;
  readonly vars: Record<string, unknown> = {};
  readonly visuals: Visual[] = [];
  parent: GameObject | null = null;
  readonly children = new Set<GameObject>();
  alive = true;
  started = false;
  /** Multiplayer: avatar controlled by another player (no local logic runs). */
  isRemote = false;
  ownerId: string | null = null;
  netId: string | null = null;
  /** Prefab this object was spawned from (for network replication). */
  prefabId: string | null = null;
  /** Generated by a TileMap etc. — not part of the saved scene. */
  generated = false;
  camera: THREE.Camera | null = null;

  private slots: BehaviourSlot[] = [];

  constructor(
    readonly runtime: Runtime,
    public data: EntityData,
  ) {
    this.id = data.id;
    this.name = data.name;
    this.tags = new Set(data.tags);
    this.object3d = new THREE.Group();
    this.object3d.name = data.name;
    this.object3d.userData.entityId = data.id;
    this.applyTransform();
    this.object3d.visible = data.enabled;
  }

  // ───────────── transform
  get position(): THREE.Vector3 {
    return this.object3d.position;
  }
  get rotation(): THREE.Euler {
    return this.object3d.rotation;
  }
  get scale(): THREE.Vector3 {
    return this.object3d.scale;
  }
  get quaternion(): THREE.Quaternion {
    return this.object3d.quaternion;
  }

  applyTransform(): void {
    const { position, rotation, scale } = this.data.transform;
    this.object3d.position.set(...position);
    this.object3d.rotation.set(rotation[0] * DEG2RAD, rotation[1] * DEG2RAD, rotation[2] * DEG2RAD);
    this.object3d.scale.set(...scale);
  }

  setPosition(x: number, y: number, z = this.position.z): this {
    this.position.set(x, y, z);
    this.runtime.physics?.teleport(this);
    return this;
  }

  /** Move relative to the current position (world axes). */
  move(x: number, y: number, z = 0): this {
    return this.setPosition(this.position.x + x, this.position.y + y, this.position.z + z);
  }

  /** Rotate by degrees. */
  rotate(x: number, y: number, z: number): this {
    this.object3d.rotateX(x * DEG2RAD);
    this.object3d.rotateY(y * DEG2RAD);
    this.object3d.rotateZ(z * DEG2RAD);
    this.runtime.physics?.teleport(this);
    return this;
  }

  /**
   * Turn so the entity's forward (-Z, same as cameras) faces a world point.
   * (three's Object3D.lookAt points +Z for non-camera objects, which would
   * make camera/light children face away.)
   */
  lookAt(x: number, y: number, z: number): this {
    const obj = this.object3d;
    obj.updateWorldMatrix(true, false);
    const eye = obj.getWorldPosition(_v);
    if (eye.distanceToSquared(_target.set(x, y, z)) < 1e-10) return this;
    _m.lookAt(eye, _target, obj.up);
    _q.setFromRotationMatrix(_m);
    if (obj.parent) _q.premultiply(obj.parent.getWorldQuaternion(_pq).invert());
    obj.quaternion.copy(_q);
    this.runtime.physics?.teleport(this);
    return this;
  }

  worldPosition(target = new THREE.Vector3()): THREE.Vector3 {
    return this.object3d.getWorldPosition(target);
  }

  /** Forward direction: -Z in 3D, +X (facing) in 2D. */
  forward(target = new THREE.Vector3()): THREE.Vector3 {
    if (this.runtime.mode2d) {
      const facing = (this.vars.facing as number) ?? 1;
      return target.set(Math.cos(this.rotation.z) * facing, Math.sin(this.rotation.z) * facing, 0);
    }
    return this.object3d.getWorldDirection(target).negate();
  }

  distanceTo(other: GameObject | THREE.Vector3): number {
    const p = other instanceof GameObject ? other.worldPosition() : other;
    return this.worldPosition(_v).distanceTo(p);
  }

  // ───────────── physics
  get velocity(): THREE.Vector3 {
    return this.runtime.physics?.getVelocity(this) ?? new THREE.Vector3();
  }

  setVelocity(x: number, y: number, z = 0): this {
    this.runtime.physics?.setVelocity(this, x, y, z);
    return this;
  }

  applyImpulse(x: number, y: number, z = 0): this {
    this.runtime.physics?.applyImpulse(this, x, y, z);
    return this;
  }

  isGrounded(): boolean {
    return this.runtime.physics?.isGrounded(this) ?? false;
  }

  // ───────────── tags, components, state
  hasTag(tag: string): boolean {
    return this.tags.has(tag);
  }
  addTag(tag: string): this {
    this.tags.add(tag);
    return this;
  }
  removeTag(tag: string): this {
    this.tags.delete(tag);
    return this;
  }

  getComponent(type: string): ComponentData | undefined {
    return this.data.components.find((c) => c.type === type && c.enabled !== false);
  }

  get visible(): boolean {
    return this.object3d.visible;
  }
  set visible(v: boolean) {
    this.object3d.visible = v;
  }

  setColor(color: string): this {
    for (const v of this.visuals) v.setColor?.(color);
    return this;
  }

  setText(text: string): this {
    for (const v of this.visuals) v.setText?.(text);
    return this;
  }

  /** Play a named model animation, if any. */
  playAnimation(name: string): this {
    for (const v of this.visuals) v.playAnimation?.(name);
    return this;
  }

  /** Walk to a point using pathfinding (needs a Nav Agent component). */
  moveTo(x: number, y: number, z = 0): this {
    this.send('moveTo', { x, y, z });
    return this;
  }

  stop(): this {
    this.send('stop');
    return this;
  }

  send(message: string, data?: unknown, from: GameObject | null = null): void {
    this.invoke('onMessage', message, data, from);
  }

  destroy(): void {
    this.runtime.destroy(this);
  }

  // ───────────── behaviours
  addBehaviour(source: string, impl: Behaviour): void {
    this.slots.push({ source, impl, failed: new Set() });
  }

  get behaviourCount(): number {
    return this.slots.length;
  }

  /** Call a hook on every behaviour; errors are isolated and reported once. */
  invoke<K extends HookName>(hook: K, ...args: Parameters<NonNullable<Behaviour[K]>>): void {
    if (this.isRemote && hook !== 'onDestroy') return;
    for (const slot of this.slots) {
      const fn = slot.impl[hook] as ((...a: unknown[]) => void) | undefined;
      if (!fn || slot.failed.has(hook)) continue;
      try {
        fn.apply(slot.impl, args);
      } catch (err) {
        slot.failed.add(hook);
        this.runtime.log({
          level: 'error',
          message: `${hook}() failed: ${errorMessage(err)} — this hook is disabled until restart.`,
          source: slot.source,
          entityId: this.id,
        });
      }
      if (!this.alive && hook !== 'onDestroy') return;
    }
  }

  dispose(): void {
    for (const v of this.visuals) v.dispose();
    this.visuals.length = 0;
    this.slots.length = 0;
  }
}
